// Helper functions for easy question retrieval
export function getQuestionsBySubjectAndLevel(
  subject: GeographySubject,
  levelId: number
): GeographyQuestion[] {
  return GEOGRAPHY_QUESTIONS.filter((q) => q.subject === subject && q.levelId === levelId);
}

export function getQuestionForBlock(
  subject: GeographySubject,
  levelId: number,
  blockIndex: number
): GeographyQuestion {
  const list = getQuestionsBySubjectAndLevel(subject, levelId);
  if (list.length === 0) {
    return GEOGRAPHY_QUESTIONS[0];
  }
  return list[blockIndex % list.length];
}

export function getRandomQuestionForSubject(
  subject: GeographySubject,
  levelId: number
): GeographyQuestion {
  const list = getQuestionsBySubjectAndLevel(subject, levelId);
  if (list.length === 0) {
    return GEOGRAPHY_QUESTIONS[0];
  }
  return list[Math.floor(Math.random() * list.length)];
}

